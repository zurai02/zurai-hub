getgenv().Config = {
    Enabled = true,
    HitPart = "Head"
}

local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")
local LocalPlayer = Players.LocalPlayer
local MouseModule = require(game:GetService("ReplicatedStorage").TREK_SERVICES.TREK_Modules.TREKMouseModule)
local mouseMeta = getmetatable(MouseModule)
local originalIndex = mouseMeta.__index

mouseMeta.__index = function(self, key)
    if not Config.Enabled then
        return originalIndex(self, key)
    end
    if key ~= "HitPosition" and key ~= "Hit" and key ~= "Target" then
        return originalIndex(self, key)
    end
    local camera = Workspace.CurrentCamera
    if not camera then
        return originalIndex(self, key)
    end
    local center = camera.ViewportSize / 2
    local closestPlayer
    local closestDistance = math.huge
    for _, player in Players:GetPlayers() do
        if player ~= LocalPlayer then
            local character = player.Character
            local targetPart = character and character:FindFirstChild(Config.HitPart)
            if targetPart then
                local screenPosition, onScreen = camera:WorldToScreenPoint(targetPart.Position)
                if onScreen then
                    local distance = (
                        Vector2.new(screenPosition.X, screenPosition.Y) - center
                    ).Magnitude
                    if distance < closestDistance then
                        closestDistance = distance
                        closestPlayer = targetPart
                    end
                end
            end
        end
    end
    if not closestPlayer then
        return originalIndex(self, key)
    end
    if key == "HitPosition" then
        return closestPlayer.Position
    elseif key == "Hit" then
        return CFrame.new(closestPlayer.Position)
    elseif key == "Target" then
        return closestPlayer
    end
    return originalIndex(self, key)
end