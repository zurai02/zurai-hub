MainTab:CreateToggle({
   Name = "Auto Buy Best Shovel",
   CurrentValue = false,
   Flag = "AutoBuyToggle",
   Callback = function(v)
      env.AutoBuy = v
      if not env.AutoBuy then return end

      task.spawn(function()
         local RarityOrder = {"Mythic", "Legendary", "Epic", "Rare", "Uncommon", "Common"}

         local function getBestShovel()
            local sharedSource = repStorage:FindFirstChild("SharedSource")
            local gameData = sharedSource and sharedSource:FindFirstChild("GameData")
            local shovelsModule = gameData and gameData:FindFirstChild("Shovels")

            if not shovelsModule then return nil end

            local shovelData = require(shovelsModule)
            local leaderstats = plr:FindFirstChild("leaderstats")
            local doubloons = leaderstats and leaderstats:FindFirstChild("Doubloons")
            if not doubloons then return nil end

            local money = doubloons.Value
            local best = nil

            for _, rarity in ipairs(RarityOrder) do
               if shovelData.GetShovelsByRarity then
                  local shovels = shovelData:GetShovelsByRarity(rarity)
                  for _, shovel in ipairs(shovels) do
                     if shovel.BaseCost and shovel.BaseCost <= money then
                        if not best or shovel.BaseCost > best.BaseCost then
                           best = shovel
                        end
                     end
                  end
                  if best then break end
               end
            end

            return best
         end

         while env.AutoBuy do
            pcall(function()
               local best = getBestShovel()
               if best then
                  local network = repStorage:FindFirstChild("Network")
                  local remoteEvents = network and network:FindFirstChild("RemoteEvents")
                  local buyEvent = remoteEvents and remoteEvents:FindFirstChild("5844c2fc64759f91")

                  if buyEvent then
                     buyEvent:FireServer({
                        ItemType = "Shovel",
                        Name = best.Name
                     })
                  end
               end
            end)
            Yield(5)
         end
      end)
   end,
})

