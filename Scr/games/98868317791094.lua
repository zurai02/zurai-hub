   CurrentValue = false,
   Flag = "StealFromAllToggle",
   Callback = function(v)
      env.stealfromall = v
      if not env.stealfromall then return end

      task.spawn(function()
         while env.stealfromall do
            pcall(function()
               local activePlots = workspace:FindFirstChild("ActivePlots")
               if activePlots then
                  for _, plot in pairs(activePlots:GetChildren()) do
                     if not env.stealfromall then break end

                     if plot.Name ~= "Plot" and plot.Name ~= tostring(plr.UserId) then
                        local network = repStorage:FindFirstChild("Network")
                        local remoteEvents = network and network:FindFirstChild("RemoteEvents")
                        local lockpickEvent = remoteEvents and remoteEvents:FindFirstChild("LockpickGateOpen")

                        if lockpickEvent then
                           lockpickEvent:FireServer(plot, 30)
                        end

                        Yield()

                        local placedItems = plot:FindFirstChild("PlacedItems")
                        if placedItems then
                           for _, item in pairs(placedItems:GetChildren()) do
                              if not env.stealfromall then break end

                              local primaryPart = item.PrimaryPart or item:FindFirstChild("PrimaryPart")
                              if primaryPart and plr.Character then
                                 plr.Character:MoveTo(primaryPart.Position)
                                 Yield(0.5)

                                 local attachment = primaryPart:FindFirstChild("Attachment")
                                 local prompt = attachment and attachment:FindFirstChildOfClass("ProximityPrompt")
                                 if prompt and typeof(fireproximityprompt) == "function" then
                                    fireproximityprompt(prompt)
                                 end

                                 Yield(0.5)

                                 local myPlot = activePlots:FindFirstChild(tostring(plr.UserId))
                                 local tpPoint = myPlot and myPlot:FindFirstChild("TeleportPoint")
                                 if tpPoint and plr.Character then
                                    plr.Character:MoveTo(tpPoint.Position)
                                 end

                                 Yield(0.5)
                              end
                           end
                        end
                     end

                     Yield()
                  end
               end
            end)
            Yield(1)
         end
      end)
