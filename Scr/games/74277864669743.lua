pcall(function()
    writefile(configPath, HttpService:JSONEncode(data))
end)

if not env.setconfig then
    env.setconfig = function(key, val)
        setdata[key] = val
        pcall(function()
            writefile(configPath, HttpService:JSONEncode(data))
        end)
    end
end

local UI, elements, Rayfield, Window, Tab, section
