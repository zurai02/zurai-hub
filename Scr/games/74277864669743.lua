        LoadingSubtitle = "by System",
        ConfigurationSaving = {
            Enabled = true,
            FolderName = "BrainrotPolice",
            FileName = "Config"
        }
    })
    Tab = Window:CreateTab("Main", 4483362458)
    section = Tab
end

local function createToggle(name, default, callback)
    if elements and section then
        elements:Toggle(name, section, default, callback)
    elseif Rayfield and section then
        section:CreateToggle({
            Name = name,
            CurrentValue = default,
            Flag = name,
            Callback = callback,
        })
    end
end

createToggle("Farm Brainrots", setdata.farmrots, function(v)
    env.setconfig("farmrots", v)
    if v then
        env.Farming = true
        task.spawn(function()
            while env.Farming do
                if workspace:FindFirstChild("Brainrots") then
                    for _, brainrot in pairs(workspace.Brainrots:GetChildren()) do
                        local rarity = brainrot:GetAttribute("Rarity")
                        if rarity == "ADMIN" or rarity == "Lucky" or rarity == "Ascendant" or rarity == "Transcendent" or rarity == "OG" then
                            if brainrot.PrimaryPart and plr.Character and plr.Character:FindFirstChild("HumanoidRootPart") then
                                plr.Character:MoveTo(brainrot.PrimaryPart.Position)
                                local model = brainrot:FindFirstChildOfClass("Model")
                                local mesh = model and model:FindFirstChildOfClass("MeshPart")
                                local prompt = mesh and mesh:FindFirstChildOfClass("ProximityPrompt")
                                if prompt then
                                    repeat
                                        fireproximityprompt(prompt)
                                        task.wait()
                                    until not brainrot or brainrot.Parent ~= workspace.Brainrots or not env.Farming
                                    task.wait(0.25)
                                    plr.Character:MoveTo(Vector3.new(7, 10, 44))
                                end
                            end
                        end
                    end
                end
                task.wait(0.1)
            end
        end)
    else
        env.Farming = false
    end
end)

