                bv.Parent = hrp
                bg.CFrame = workspace.CurrentCamera.CoordinateFrame
                bv.Velocity = workspace.CurrentCamera.CFrame.LookVector * 50
                task.wait()
            end
            bg:Destroy()
            bv:Destroy()
        end)
    end
end)
