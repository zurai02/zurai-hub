createToggle("Auto Collect", setdata.farmcollect, function(v)
    env.setconfig("farmcollect", v)
    if v then
        env.AutoCollect = true
        task.spawn(function()
            while env.AutoCollect do
                if workspace:FindFirstChild("Plots") then
                    for _, plot in pairs(workspace.Plots:GetChildren()) do
                        if plot:GetAttribute("Owner") == plr.UserId then
                            local podiums = plot:FindFirstChild("Podiums")
                            if podiums then
                                for _, pod in pairs(podiums:GetChildren()) do
                                    local collectPart = pod:FindFirstChild("Collect")
                                    if collectPart and plr.Character and plr.Character:FindFirstChild("Head") then
                                        firetouchinterest(plr.Character.Head, collectPart, true)
                                        task.wait()
                                        firetouchinterest(plr.Character.Head, collectPart, false)
                                    end
                                end
                            end
                        end
                    end
                end
                task.wait(2)
            end
        end)
    else
        env.AutoCollect = false
    end
end)

