local Window = keoirn:CreateWindow({
   Name = "zurai-hub",
   Theme = "amethyst",
   Subtitle = "zurai-hub",
   SidebarLayout = true,
   Configuration = {
      autoSave = true,
      autoLoad = true,
      customFolder = "zurai-hub",
      fileName = "Config"
   }
})

local MainTab = Window:CreateTab("Main", 4483362458)
local PlayerTab = Window:CreateTab("Player", 4483362458)

MainTab:CreateSection("Farming Options")

MainTab:CreateToggle({
   Name = "Auto Money",
   CurrentValue = false,
   Flag = "AutoMoneyToggle",
   Callback = function(v)
      env.AutoMoney = v
      if not v then return end

      task.spawn(function()
         while env.AutoMoney do
            task.spawn(function()
               local remote = game:GetService("ReplicatedStorage"):FindFirstChild("ModifiedPackages") and game.ReplicatedStorage.ModifiedPackages:FindFirstChild("Packet") and game.ReplicatedStorage.ModifiedPackages.Packet:FindFirstChild("RemoteEvent")
               if remote then
                  remote:FireServer(buffer.fromstring("\x0E"))
               end
            end)
            Yield()
         end
      end)
   end,
})

MainTab:CreateToggle({
   Name = "Auto Rebirth",
   CurrentValue = false,
   Flag = "AutoRebirthToggle",
   Callback = function(v)
      env.AutoRebirth = v
      if not v then return end

      task.spawn(function()
         while env.AutoRebirth do
            pcall(function()
               local remote = game:GetService("ReplicatedStorage"):FindFirstChild("ModifiedPackages") and game.ReplicatedStorage.ModifiedPackages:FindFirstChild("Packet") and game.ReplicatedStorage.ModifiedPackages.Packet:FindFirstChild("RemoteEvent")
               if remote then
                  remote:FireServer(buffer.fromstring("\x93"))
               end
            end)
            Yield(1)
         end
      end)
   end,
})

PlayerTab:CreateSection("Player Tweaks")

