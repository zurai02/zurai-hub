local SafeExecutionWrapper = {}
function SafeExecutionWrapper.Execute(callback, ...)
    local success, result = pcall(callback, ...)
    if not success then
        SystemState.FaultCount = SystemState.FaultCount + 1
        TelemetrySubsystem.LogEvent("ExecutionError", {Error = tostring(result)})
        return nil
    end
    return result
end

local PipelineExecutionTracker = {}
function PipelineExecutionTracker.Track(name, func, ...)
    local start = tick_os()
    local res = SafeExecutionWrapper.Execute(func, ...)
    local duration = tick_os() - start
    TelemetrySubsystem.LogEvent("PipelineExecution", {Name = name, Duration = duration})
    return res
end

