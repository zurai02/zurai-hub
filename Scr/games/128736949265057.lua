local MathUtils = {}
function MathUtils.RoundVector(vector)
    return Vector3.new(
        math.floor(vector.X + 0.5),
        math.floor(vector.Y + 0.5),
        math.floor(vector.Z + 0.5)
    )
end

function MathUtils.CalculateDistance(posA, posB)
    return (posA - posB).Magnitude
end

function MathUtils.ClampVector(vec, minVal, maxVal)
    return Vector3.new(
        math_clamp(vec.X, minVal, maxVal),
        math_clamp(vec.Y, minVal, maxVal),
        math_clamp(vec.Z, minVal, maxVal)
    )
end

local TelemetrySubsystem = {}
function TelemetrySubsystem.LogEvent(category, data)
    if not Config.TelemetryEnabled then return end
    local entry = {
        Timestamp = tick_os(),
        Category = category,
        Data = data,
        Id = HttpService:GenerateGUID(false)
    }
    table_insert(storageRegistry.TelemetryLog, entry)
    if #storageRegistry.TelemetryLog > Config.MaxHistoryEntries then
        table_remove(storageRegistry.TelemetryLog, 1)
    end
end

function TelemetrySubsystem.DumpMetrics()
    local metrics = {
        ActiveConnections = #storageRegistry.Connections,
        RegisteredStates = 0,
        Uptime = tick_os()
    }
    for _ in pairs(storageRegistry.OriginalStates) do
        metrics.RegisteredStates = metrics.RegisteredStates + 1
    end
    return metrics
end

local PropertyManager = {}
function PropertyManager.CaptureState(part)
    if not storageRegistry.OriginalStates[part] then
        storageRegistry.OriginalStates[part] = {
            Size = part.Size,
            Transparency = part.Transparency,
            BrickColor = part.BrickColor,
            CanCollide = part.CanCollide,
            Material = part.Material,
            Reflectance = part.Reflectance
        }
    end
end

function PropertyManager.RestoreState(part)
    local state = storageRegistry.OriginalStates[part]
    if state and part and part.Parent then
        part.Size = state.Size
        part.Transparency = state.Transparency
        part.BrickColor = state.BrickColor
        part.CanCollide = state.CanCollide
        part.Material = state.Material
        part.Reflectance = state.Reflectance
    end
    storageRegistry.OriginalStates[part] = nil
end

local function modifyBasePart(rootPart)
    if not rootPart or not rootPart:IsA("BasePart") then return end
    PropertyManager.CaptureState(rootPart)
    if rootPart.Size ~= Config.HitboxSize then
        rootPart.Size = Config.HitboxSize
        rootPart.Transparency = Config.HitboxTransparency
        rootPart.BrickColor = Config.HitboxColor
        rootPart.CanCollide = false
    end
    SystemState.TotalProcessedCharacters = SystemState.TotalProcessedCharacters + 1
    TelemetrySubsystem.LogEvent("ModifyBasePart", {PartName = rootPart.Name})
end

local function processCharacter(character)
    if not character then return end
    local rootPart = character:WaitForChild("HumanoidRootPart", 5)
    if rootPart then 
        modifyBasePart(rootPart) 
    end
    
    local parentSignal = character:GetPropertyChangedSignal("Parent"):Connect(function()
        if character.Parent and rootPart then 
            modifyBasePart(rootPart) 
        end
    end)
    table_insert(storageRegistry.Connections, parentSignal)
    SystemState.ActiveConnections = #storageRegistry.Connections
end

local function registerPlayer(player)
    if player == LocalPlayer then return end
    if player.Character then 
        processCharacter(player.Character) 
    end
    local charSignal = player.CharacterAdded:Connect(processCharacter)
    table_insert(storageRegistry.Connections, charSignal)
    SystemState.ActiveConnections = #storageRegistry.Connections
end

local existingPlayers = Players:GetPlayers()
for i = 1, #existingPlayers do 
    registerPlayer(existingPlayers[i]) 
end

local playerAddedSignal = Players.PlayerAdded:Connect(registerPlayer)
table_insert(storageRegistry.Connections, playerAddedSignal)

local NetworkInterceptor = {}
local oldNamecall
oldNamecall = hookmetamethod(game, "__namecall", function(self, ...)
    local method = getnamecallmethod()
    if method == "FireServer" or method == "InvokeServer" then
        local remoteName = self.Name
        if remoteName == "AttackRemote" or remoteName == "HitRemote" then
            if isRemoteValid then
                local currentTime = tick_os()
                if currentTime - storageRegistry.LastParryTime >= Config.ParryCooldown then
                    storageRegistry.LastParryTime = currentTime
                    parryRemote:FireServer(true)
                    TelemetrySubsystem.LogEvent("ParryTriggered", {Timestamp = currentTime})
                end
            end
        end
    end
    return oldNamecall(self, ...)
end)

local function flushBuffer()
    for i = 1, #storageRegistry.Connections do
        local connection = storageRegistry.Connections[i]
        if connection and connection.Connected then 
            connection:Disconnect() 
        end
    end
    table_clear(storageRegistry.Connections)
    
    for part, state in pairs(storageRegistry.OriginalStates) do
        if part and part.Parent then
            part.Size = state.Size
            part.Transparency = state.Transparency
            part.BrickColor = state.BrickColor
            part.CanCollide = state.CanCollide
            part.Material = state.Material
            part.Reflectance = state.Reflectance
        end
    end
    table_clear(storageRegistry.OriginalStates)
    SystemState.ActiveConnections = 0
    TelemetrySubsystem.LogEvent("BufferFlushed", {})
end

Players.PlayerRemoving:Connect(function(player)
    if #storageRegistry.Connections > Config.MaxConnectionBuffer then
        flushBuffer()
        local activePlayers = Players:GetPlayers()
        for i = 1, #activePlayers do 
            registerPlayer(activePlayers[i]) 
        end
        local reAddSignal = Players.PlayerAdded:Connect(registerPlayer)
        table_insert(storageRegistry.Connections, reAddSignal)
    end
end)

local DiagnosticTask = RunService.Stepped:Connect(function()
    local currentTime = tick_os()
    if currentTime - SystemState.LastExecutionTime >= Config.UpdateInterval then
        SystemState.LastExecutionTime = currentTime
        SystemState.MemoryPressure = collectgarbage("count")
        if SystemState.MemoryPressure > 100000 then
            collectgarbage("collect")
        end
    end
end)
table_insert(storageRegistry.Connections, DiagnosticTask)

local RegistryValidator = {}
function RegistryValidator.VerifyIntegrity()
    local validCount = 0
    for i = 1, #storageRegistry.Connections do
        local conn = storageRegistry.Connections[i]
        if conn then
            validCount = validCount + 1
        end
    end
    return validCount == #storageRegistry.Connections
end

local PipelineManager = {}
function PipelineManager.ExecutePipelineCycle()
    local activePlayers = Players:GetPlayers()
    for i = 1, #activePlayers do
        local player = activePlayers[i]
        if player ~= LocalPlayer and player.Character then
            local hrp = player.Character:FindFirstChild("HumanoidRootPart")
            if hrp then
                modifyBasePart(hrp)
            end
        end
    end
end

local RoutineDispatcher = {}
function RoutineDispatcher.SpawnWorker(func)
    local success, err = pcall(func)
    if not success then
        SystemState.FaultCount = SystemState.FaultCount + 1
        TelemetrySubsystem.LogEvent("WorkerFault", {Error = tostring(err)})
    end
end

