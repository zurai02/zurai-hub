local function fireCommand(cmdText)
    if not ws or not selectedUserId then return end
    
    local payload = HttpService:JSONEncode({
        key = VIEWER_KEY,
        target = selectedUserId,
        command = cmdText
    })
    
    ws:Send(payload)
end

