local function parseValue(str)
    local suffixes = {
        K = 1e3,
        M = 1e6,
        B = 1e9,
        T = 1e12,
        Q = 1e15,
    }
    
    local num, suffix = str:match("^([%d%.]+)([A-Za-z]*)")
    if not num then return 0 end
    
    num = tonumber(num) or 0
    suffix = suffix:upper()
    
    if suffixes[suffix] then
        return num * suffixes[suffix]
    end
    
    return num
end

