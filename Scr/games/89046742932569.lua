MainTab:CreateToggle({
   Name = "Autofarm",
   CurrentValue = false,
   Flag = "AutofarmToggle",
   Callback = function(v)
      env.Farming = v
      if not v then return end

      task.spawn(function()
         while env.Farming do
            pcall(function()
               local zonesFold = workspace:FindFirstChild("Zones")
               local chosenZone = zonesFold and zonesFold:FindFirstChild("Zone" .. tostring(env.ChosenZoneNum))
               
               if chosenZone and chosenZone:FindFirstChild("Objects") and plr.Character then
                  for _, brainrot in pairs(chosenZone.Objects:GetChildren()) do
                     if not env.Farming then break end

                     if brainrot.PrimaryPart then
                        plr.Character:MoveTo(brainrot.PrimaryPart.Position)
                     end

                     repeat
                        local prompt = brainrot:FindFirstChild("ProximityPrompt") or (brainrot.PrimaryPart and brainrot.PrimaryPart:FindFirstChild("ProximityPrompt"))
                        if prompt and typeof(fireproximityprompt) == "function" then
                           fireproximityprompt(prompt)
                        end
                        Yield()
                     until not brainrot or brainrot.Parent ~= chosenZone.Objects or not env.Farming

                     local playerBase = workspace:FindFirstChild("Bases") and workspace.Bases:FindFirstChild(plr.Name)
                     if playerBase and playerBase:FindFirstChild("Root") and plr.Character then
                        plr.Character:MoveTo(playerBase.Root.Position)
                     end
                     Yield(0.5)
                  end
               end
            end)
            Yield(1)
         end
      end)
   end,
})

