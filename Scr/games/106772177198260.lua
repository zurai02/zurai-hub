local Yield = task.wait
local plr = game:GetService("Players").LocalPlayer
local repStorage = game:GetService("ReplicatedStorage")
local env = getgenv()

env.Farming = false

local Rayfield = loadstring(game:HttpGet("https://sirius.menu/rayfield"))()

local Window = Rayfield:CreateWindow({
   Name = "zurai02",
   LoadingTitle = "Loading Script...",
   LoadingSubtitle = "by zurai02",
   ConfigurationSaving = {
      Enabled = true,
      FolderName = "BrainrotPolice",
      FileName = "ReelForBrainrotsConfig"
   }
})

local MainTab = Window:CreateTab("Main", 4483362458)
local PlayerTab = Window:CreateTab("Player", 4483362458)

MainTab:CreateSection("Farming Options")

MainTab:CreateToggle({
   Name = "Farming",
   CurrentValue = false,
   Flag = "ReelFarmingToggle",
   Callback = function(isOn)
      env.Farming = isOn
      if not isOn then return end

      task.spawn(function()
         while env.Farming do
            pcall(function()
               local remoteHandler = repStorage:FindFirstChild("RemoteHandler")
               local fishingRemote = remoteHandler and remoteHandler:FindFirstChild("Fishing")
               
               if fishingRemote then
                  fishingRemote:FireServer("Caught", 3)
               end
            end)
            Yield(0.1)
         end
      end)
   end,
})

MainTab:CreateButton({
   Name = "Dupe Brainrot InHand",
   Callback = function()
      local char = plr.Character
      if char then
         local br = char:FindFirstChildOfClass("Tool")
         if br and br:GetAttribute("brainrot") then
            task.spawn(function()
               for plotNum = 1, 30 do
                  local remoteHandler = repStorage:FindFirstChild("RemoteHandler")
                  local placeEv = remoteHandler and remoteHandler:FindFirstChild("Plot")
                  
                  if placeEv then
                     placeEv:FireServer("Add", "Plot" .. plotNum, br.Name)
                  end
                  Yield(0.5)
               end
            end)
         end
      end
   end,
})

PlayerTab:CreateSection("Player Tweaks")

PlayerTab:CreateSlider({
   Name = "WalkSpeed",
   Range = {16, 250},
   Increment = 1,
   Suffix = "Speed",
   CurrentValue = 16,
   Flag = "SpeedSlider",
   Callback = function(val)
      if plr.Character and plr.Character:FindFirstChildOfClass("Humanoid") then
         plr.Character:FindFirstChildOfClass("Humanoid").WalkSpeed = val
      end
   end,
})

PlayerTab:CreateSlider({
   Name = "JumpPower",
   Range = {50, 300},
   Increment = 5,
   Suffix = "Power",
   CurrentValue = 50,
   Flag = "JumpSlider",
   Callback = function(val)
      if plr.Character and plr.Character:FindFirstChildOfClass("Humanoid") then
         local hum = plr.Character:FindFirstChildOfClass("Humanoid")
         hum.UseJumpPower = true
         hum.JumpPower = val
      end
   end,
})
