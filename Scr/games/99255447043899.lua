local Yield = task.wait
local plr = game:GetService("Players").LocalPlayer
local env = getgenv()

env.Farming = false
env.Autosell = false

local Rayfield = loadstring(game:HttpGet("https://sirius.menu/rayfield"))()

local Window = Rayfield:CreateWindow({
   Name = "zurai02",
   LoadingTitle = "Loading Script...",
   LoadingSubtitle = "by zurai02",
   ConfigurationSaving = {
      Enabled = true,
      FolderName = "zurai-hub",
      FileName = "BecomeABrainrotConfig"
   }
})

local MainTab = Window:CreateTab("Main", 4483362458)
local PlayerTab = Window:CreateTab("Player", 4483362458)

MainTab:CreateSection("Farming Options")

local maxedCon

MainTab:CreateToggle({
   Name = "Autoequip + Sell when maxed",
   CurrentValue = false,
   Flag = "AutoSellToggle",
   Callback = function(v)
      env.Autosell = v
      if not v then 
         if maxedCon then maxedCon:Disconnect() end 
         return 
      end

      local replicatedStorage = game:GetService("ReplicatedStorage")
      local events = replicatedStorage:FindFirstChild("Events")
      
      if events and events:FindFirstChild("Notify") then
         maxedCon = events.Notify.OnClientEvent:Connect(function(arg1)
            if typeof(arg1) == "string" and arg1:find("Max 75") then
               if events:FindFirstChild("EquipBest") then
                  events.EquipBest:FireServer()
               end

               Yield(1)

               if events:FindFirstChild("SellAllBrainrots") and plr:FindFirstChild("Backpack") then
                  events.SellAllBrainrots:FireServer(plr.Backpack:GetChildren())
               end
            end
         end)
      end
   end,
})

MainTab:CreateToggle({
   Name = "Autofarm",
   CurrentValue = false,
   Flag = "AutofarmToggle",
   Callback = function(v)
      env.Farming = v
      if not v then return end

      task.spawn(function()
         while env.Farming do
            pcall(function()
               local runTrigger = workspace:FindFirstChild("RunTrigger")
               local locations = workspace:FindFirstChild("Locations")
               local brainrotsFolder = locations and locations:FindFirstChild("End") and locations.End:FindFirstChild("Brainrots")
               local escapeHitbox = workspace:FindFirstChild("EscapeHitbox")

               if runTrigger and plr.Character and plr.Character:FindFirstChild("Head") and typeof(firetouchinterest) == "function" then
                  firetouchinterest(plr.Character.Head, runTrigger, 0)
                  Yield()
                  firetouchinterest(plr.Character.Head, runTrigger, 1)
               end

               Yield(0.5)

               if plr.Character then
                  plr.Character:MoveTo(Vector3.new(46, 4, -1816))
               end

               if brainrotsFolder then
                  local firstbr
                  repeat
                     firstbr = brainrotsFolder:FindFirstChildOfClass("Model")
                     Yield()
                  until firstbr or not env.Farming

                  local bestbr = nil
                  local mostval = 0

                  for _, item in pairs(brainrotsFolder:GetChildren()) do
                     local moneyVal = item:FindFirstChild("MoneyPerSecond")
                     local prompt = item.PrimaryPart and item.PrimaryPart:FindFirstChildOfClass("ProximityPrompt")

                     if moneyVal and prompt and prompt.ActionText ~= "STEAL OP" then
                        if moneyVal.Value > mostval then
                           mostval = moneyVal.Value
                           bestbr = item
                        end
                     end
                  end

                  if bestbr and bestbr.PrimaryPart then
                     if plr.Character then
                        plr.Character:MoveTo(bestbr.PrimaryPart.Position)
                     end
                     Yield()

                     local prompt = bestbr.PrimaryPart:FindFirstChildOfClass("ProximityPrompt")
                     repeat
                        if prompt and typeof(fireproximityprompt) == "function" then
                           fireproximityprompt(prompt)
                        end
                        Yield()
                     until not bestbr or bestbr.Parent ~= brainrotsFolder or not env.Farming

                     Yield()

                     if escapeHitbox and plr.Character then
                        plr.Character:MoveTo(escapeHitbox.Position)
                     end
                  end
               end
            end)
            Yield(1)
         end
      end)
   end,
})

