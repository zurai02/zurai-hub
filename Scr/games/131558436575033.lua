local plrs = game:GetService("Players")
local ws = game:GetService("Workspace")
local rs = game:GetService("RunService")
local me = plrs.LocalPlayer

local Config = {
    FOV = 300,
}

local function target()
    local camera = ws.CurrentCamera
    if not camera then return end
    local center = camera.ViewportSize / 2
    local bestDist, bestPart = Config.FOV, nil
    for _, player in plrs:GetPlayers() do
        if player == me then continue end
        local char = player.Character
        if not char then continue end
        local hum = char:FindFirstChildOfClass("Humanoid")
        if not hum or hum.Health <= 0 then continue end
        for _, part in { char:FindFirstChild("Head"), char:FindFirstChild("UpperTorso") or char:FindFirstChild("Torso"), char:FindFirstChild("HumanoidRootPart"), char:FindFirstChild("LeftUpperArm"), char:FindFirstChild("RightUpperArm") } do
            if not part then continue end
            local pos, onScreen = camera:WorldToViewportPoint(part.Position)
            if not onScreen then continue end
            local dist = (Vector2.new(pos.X, pos.Y) - center).Magnitude
            if dist < bestDist then
                bestDist, bestPart = dist, part
            end
        end
    end
    return bestPart
end

local script = require(me.PlayerScripts.App.Modules.Weapon.AimAssist)
local hook; hook = hookfunction(script.pull, newcclosure(function(origin, direction)
    local target = target()
    if target then
        local delta = target.Position - origin
        if delta.Magnitude > 0.001 then return delta.Unit end
    end
    return hook(origin, direction)
end))

local FOV = Drawing.new("Circle")
FOV.Thickness = 1.5
FOV.NumSides = 64
FOV.Radius = Config.FOV
FOV.Filled = false
FOV.Color = Color3.fromRGB(255, 255, 255)
FOV.Transparency = 0.8
FOV.Visible = true

rs.RenderStepped:Connect(function()
    FOV.Position = ws.CurrentCamera.ViewportSize / 2
end)