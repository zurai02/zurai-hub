local originalNew = Projectile.new
Projectile.new = function(params)
    if CONFIG.Enabled and params and params.Origin and params.Direction then
        local head = getClosestHead()
        if head then
            local newDir = (head.Position - params.Origin).Unit
            params.Direction = newDir
        end
    end
    return originalNew(params)
end