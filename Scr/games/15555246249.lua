uiCorner.CornerRadius = UDim.new(0, 8)
uiCorner.Parent = toggleButton

local tweenInfo = TweenInfo.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out)

toggleButton.MouseButton1Click:Connect(function()
    CONFIG.Enabled = not CONFIG.Enabled
    local targetColor = CONFIG.Enabled and Color3.fromRGB(40, 160, 60) or Color3.fromRGB(180, 40, 40)
    local targetText = CONFIG.Enabled and "Enabled: ON" or "Enabled: OFF"
    toggleButton.Text = targetText
    TweenService:Create(toggleButton, tweenInfo, {BackgroundColor3 = targetColor}):Play()
end)

local targetPos = nil

local function getClosestTarget()
    if not CONFIG.Enabled then
        targetPos = nil
        return
    end

    local camera = workspace.CurrentCamera
    local mousePos = UserInputService:GetMouseLocation()
    local closestDist = math.huge
    local closestPos = nil
    
    for _, player in ipairs(Players:GetPlayers()) do
        if player == LocalPlayer then continue end
        local char = player.Character
        if not char then continue end
        local head = char:FindFirstChild("Head")
        if not head then continue end
        local screenPos, onScreen = camera:WorldToViewportPoint(head.Position)
        if not onScreen then continue end
        local dist = (Vector2.new(screenPos.X, screenPos.Y) - mousePos).Magnitude
        if dist < closestDist then
            closestDist = dist
            closestPos = head.Position
        end
    end
    targetPos = closestPos
end

local oldNamecall
oldNamecall = hookmetamethod(game, "__namecall", newcclosure(function(self, ...)
    local method = getnamecallmethod():lower()
    if CONFIG.Enabled and method == "raycast" and targetPos and typeof(self) == "Instance" and self == workspace then
        local args = {...}
        if typeof(args[1]) == "Vector3" then
            local camera = workspace.CurrentCamera
            args[2] = (targetPos - camera.CFrame.Position).Unit * 500
            
            local _unpack = unpack or table.unpack
            return oldNamecall(self, _unpack(args))
        end
    end
    return oldNamecall(self, ...)
end))

RunService.Heartbeat:Connect(getClosestTarget)