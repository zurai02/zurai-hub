   Name = "Farming",
   CurrentValue = false,
   Flag = "WingsFarmToggle",
   Callback = function(value)
      env.farming = value
   end,
})

MainTab:CreateButton({
   Name = "Teleport to Spawn",
   Callback = function()
      teleportTo(worldPositions.spawn)
   end,
})

