local plrs = game:GetService("Players")
local rs = game:GetService("RunService")
local you = plrs.LocalPlayer
local target

local function getTarget()
    local cam = workspace.CurrentCamera
    local screendistance = math.huge
    local closesttocenter
    local center = Vector2.new(cam.ViewportSize.X / 2, cam.ViewportSize.Y / 2)
    for _, plr in ipairs(plrs:GetPlayers()) do
        if plr == you then continue end
        local char = plr.Character
        if not char then continue end
        local hrp = char:FindFirstChild("HumanoidRootPart")
        local hum = char:FindFirstChildOfClass("Humanoid")
        if not hrp or not hum or hum.Health <= 0 then continue end
        local screenPos, onScreen = cam:WorldToViewportPoint(hrp.Position)
        if not onScreen then continue end
        local dist = (Vector2.new(screenPos.X, screenPos.Y) - center).Magnitude
        if dist < screendistance then
            screendistance = dist
            closesttocenter = hrp.Position + Vector3.new(0, 0.5, 0)
        end
    end
    target = closesttocenter
end

local main; main = hookmetamethod(game, "__newindex", newcclosure(function(self, key, value)
    if target and typeof(self) == "Instance" and self:IsA("BasePart") and
       key == "CFrame" and typeof(value) == "CFrame" then
        return main(self, key, CFrame.new(value.Position, target))
    end
    return main(self, key, value)
end))

rs.Heartbeat:Connect(getTarget)