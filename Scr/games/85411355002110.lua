local HttpService = game:GetService("HttpService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Players = game:GetService("Players")
local LocalPlayer = Players.LocalPlayer

local configPath = "BrainrotPolice/Config.json"
local data = {}
if pcall(function() return readfile(configPath) end) then
    local success, decoded = pcall(function() return HttpService:JSONDecode(readfile(configPath)) end)
    if success then data = decoded end
end

local placeIdKey = tostring(game.PlaceId)
data[placeIdKey] = data[placeIdKey] or {}
data[placeIdKey].farmrots = data[placeIdKey].farmrots or false
writefile(configPath, HttpService:JSONEncode(data))

local env = getgenv()
env.Farming = false

local endPos = Vector3.new(-74, 63, 15784)
local colPos = Vector3.new(-74, 20, -447)

local Rayfield = loadstring(game:HttpGet('https://sirius.menu/rayfield'))()

local Window = Rayfield:CreateWindow({
    Name = "+1 Dash for Brainrots",
    LoadingTitle = "Loading...",
    LoadingSubtitle = "Interface",
    ConfigurationSaving = {
        Enabled = true,
        FolderName = "zurai-hub",
        FileName = "Config"
    }
})

local Tab = Window:CreateTab("Main", 4483362458)

Tab:CreateToggle({
    Name = "Farm Brainrots",
    CurrentValue = data[placeIdKey].farmrots,
    Flag = "FarmRots",
    Callback = function(v)
        data[placeIdKey].farmrots = v
        writefile(configPath, HttpService:JSONEncode(data))
        env.Farming = v
        if v then
            task.spawn(function()
                while env.Farming do
                    local char = LocalPlayer.Character
                    if char and char:FindFirstChild("HumanoidRootPart") then
                        char:MoveTo(endPos)
                    end
                    
                    local spawners = workspace:FindFirstChild("Map") and workspace.Map:FindFirstChild("Spawners")
                    local luckFolder = spawners and spawners:FindFirstChild("???xLuck")
                    local lastPlace = luckFolder and luckFolder:FindFirstChild("???")

                    if lastPlace then
                        pcall(function()
                            for _, child in pairs(lastPlace:GetChildren()) do
                                if not child:IsA("Model") then continue end

                                while LocalPlayer.GameplayPaused and env.Farming do
                                    task.wait()
                                end

                                if not child.PrimaryPart then continue end
                                
                                local currentLocChar = LocalPlayer.Character
                                if currentLocChar and currentLocChar:FindFirstChild("HumanoidRootPart") then
                                    currentLocChar:MoveTo(child.PrimaryPart.Position)
                                end
                                
                                local prox = child.PrimaryPart:FindFirstChildOfClass("ProximityPrompt")
                                if prox then
                                    repeat
                                        fireproximityprompt(prox)
                                        task.wait()
                                    until not child or child.Parent ~= lastPlace or not env.Farming
                                end

                                yield(0.5)
                                
                                repeat
                                    local movingChar = LocalPlayer.Character
                                    if movingChar and movingChar:FindFirstChild("HumanoidRootPart") then
                                        movingChar:MoveTo(colPos)
                                    end
                                    task.wait()
                                until not LocalPlayer.Character or not LocalPlayer.Character:FindFirstChildOfClass("Model") or not env.Farming
                                
                                break
                            end
                        end)
                    end
                    yield()
                end
            end)
        end
    end,
})

Rayfield:LoadConfiguration()
