local LocalPlayer = Players.LocalPlayer
local Camera = Workspace.CurrentCamera

local Config = {
    SilentAim = true,
    SilentAimFOV = 150,
    TargetPart = "Head",
    MaxDistance = 4500,
    Wallbang = true,
    InstantHit = true,
    ZeroRecoil = true,
    ZeroSpread = true,
    FastFirerate = true,
    OneShotKill = false,
