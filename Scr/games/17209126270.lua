local rs = game:GetService("ReplicatedStorage")
local plrs = game:GetService("Players")
local lplr = plrs.LocalPlayer
local yield = task.Wait

if not lplr.Character then
	lplr.CharacterAdded:Wait()
end
yield(1)

local path1 = rs:WaitForChild("ACS_Engine")
local path2 = path1:WaitForChild("Modules")
local path3 = path2:WaitForChild("FastCastRedux")
local path4 = require(path3)
local path5 = path3:WaitForChild("ActiveCast")
local path6 = require(path5)

local function target(cam)
	local viewport = cam.ViewportSize / 2
	local best = math.huge
	local targett = nil
	for _, player in plrs:GetPlayers() do
		if player ~= lplr then
			local character = player.Character
			if character then
				local root = character:FindFirstChild("HumanoidRootPart")
				local humanoid = character:FindFirstChildOfClass("Humanoid")
				if root and humanoid and humanoid.Health > 0 then
					local screenPos, onScreen = cam:WorldToViewportPoint(root.Position)
					if onScreen and screenPos.Z > 0 then
						local dist = (Vector2.new(screenPos.X, screenPos.Y) - viewport).Magnitude
						if dist < best then
							best = dist
							targett = root
						end
					end
				end
			end
		end
	end
	return targett
end

local cast = path6.new
function path6.new(caster, origin, direction, speed, behavior)
	local cam = workspace.CurrentCamera
	if cam and typeof(origin) == "Vector3" and typeof(direction) == "Vector3" then
		local target = target(cam)
		if target then
			local toTarget = target.Position - origin
			if toTarget.Magnitude > 1e-4 then
				direction = toTarget.Unit
			end
		end
	end
	return cast(caster, origin, direction, speed, behavior)
end