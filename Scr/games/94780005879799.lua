local HttpService = game:GetService("HttpService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Players = game:GetService("Players")
local LocalPlayer = Players.LocalPlayer

local configPath = "zurai-hub/Config.json"
local data = {}
if pcall(function() return readfile(configPath) end) then
    local success, decoded = pcall(function() return HttpService:JSONDecode(readfile(configPath)) end)
    if success then data = decoded end
end

local placeIdKey = tostring(game.PlaceId)
data[placeIdKey] = data[placeIdKey] or {}
data[placeIdKey].addspins = data[placeIdKey].addspins or false
data[placeIdKey].farmsleepy = data[placeIdKey].farmsleepy or false
data[placeIdKey].farmog = data[placeIdKey].farmog or false
writefile(configPath, HttpService:JSONEncode(data))

local env = getgenv()
env.AddingSpins = false
env.AutoSleepy = false
env.AutoOg = false

local Rayfield = loadstring(game:HttpGet('https://sirius.menu/rayfield'))()

local Window = Rayfield:CreateWindow({
    Name = "Scream for Brainrots",
    LoadingTitle = "Loading...",
    LoadingSubtitle = "zurai-hub",
    ConfigurationSaving = {
        Enabled = true,
        FolderName = "zurai-hub",
        FileName = "Config"
    }
})

local Tab = Window:CreateTab("Main", 4483362458)

Tab:CreateToggle({
    Name = "Add Inf Spins",
    CurrentValue = data[placeIdKey].addspins,
    Flag = "AddSpins",
    Callback = function(v)
        data[placeIdKey].addspins = v
        writefile(configPath, HttpService:JSONEncode(data))
        env.AddingSpins = v
        if v then
            task.spawn(function()
                while env.AddingSpins do
                    local Event = ReplicatedStorage.Remotes:FindFirstChild("AddSpin")
                    if Event then
                        Event:FireServer()
                    end
                    task.wait()
                end
            end)
        end
    end,
})

Tab:CreateToggle({
    Name = "Auto Spin Sleepy Mutation",
    CurrentValue = data[placeIdKey].farmsleepy,
    Flag = "AutoSleepy",
    Callback = function(v)
        data[placeIdKey].farmsleepy = v
        writefile(configPath, HttpService:JSONEncode(data))
        env.AutoSleepy = v
        if v then
            task.spawn(function()
                while env.AutoSleepy do
                    local Event = ReplicatedStorage.Remotes:FindFirstChild("SpinEventWheel")
                    if Event then
                        Event:FireServer(5)
                    end
                    task.wait(0.5)
                end
            end)
        end
    end,
})

Tab:CreateToggle({
    Name = "Auto Spin OG",
    CurrentValue = data[placeIdKey].farmog,
    Flag = "AutoOg",
    Callback = function(v)
        data[placeIdKey].farmog = v
        writefile(configPath, HttpService:JSONEncode(data))
        env.AutoOg = v
        if v then
            task.spawn(function()
                while env.AutoOg do
                    local Event = ReplicatedStorage.Remotes:FindFirstChild("SpinEventWheel")
                    if Event then
                        Event:FireServer(4)
                    end
                    task.wait(0.5)
                end
            end)
        end
    end,
})

Rayfield:LoadConfiguration()
