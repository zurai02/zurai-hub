local Yield = task.wait
local plr = game:GetService("Players").LocalPlayer
local env = getgenv()

env.Farming = false
env.Farminga = false

local keoirn = loadstring(game:HttpGet("https://raw.githubusercontent.com/Zeoirn/keoirn/refs/heads/main/Keoirn.lua"))()

local Window = keoirn:CreateWindow({
   Name = "skate for brainrots",
   Theme = "amethyst",
   SidebarLayout = true,
   Configuration = {
      autoSave = true,
      autoLoad = true,
      customFolder = "zurai-hub",
      fileName = "Config"
   }
})
local MainTab = Window:CreateTab("Main", 4483362458)
local PlayerTab = Window:CreateTab("Player", 4483362458)

MainTab:CreateSection("Farming Options")

MainTab:CreateToggle({
   Name = "Farm OG + Celestial Brainrots",
   CurrentValue = false,
   Flag = "FarmOGCelestialToggle",
   Callback = function(v)
      env.Farming = v
      if not v then return end

      task.spawn(function()
         while env.Farming do
            pcall(function()
               local brainrotsFolder = workspace:FindFirstChild("Bin") and workspace.Bin:FindFirstChild("FieldBrainrots")
               if brainrotsFolder then
                  for _, br in pairs(brainrotsFolder:GetChildren()) do
                     if not env.Farming then break end

                     local fieldName = br:GetAttribute("FieldName")
                     local traits = br:GetAttribute("Traits")

                     if (fieldName == "CelestialField" or fieldName == "OGField") and traits ~= "VIP" then
                        if plr.Character then
                           plr.Character:MoveTo(br.Position)
                        end

                        repeat
                           local prompt = br:FindFirstChildOfClass("ProximityPrompt")
                           if prompt and typeof(fireproximityprompt) == "function" then
                              fireproximityprompt(prompt)
                           end
                           Yield()
                        until not br or br.Parent ~= brainrotsFolder or not env.Farming

                        Yield()

                        repeat
                           if plr.Character then
                              plr.Character:MoveTo(Vector3.new(69, 30, 162))
                           end
                           Yield()
                        until not plr.Character or not plr.Character:FindFirstChild("HeldFieldBrainrot") or not env.Farming

                        Yield()
                     end
                  end
               end
            end)
            Yield(0.1)
         end
      end)
   end,
})

