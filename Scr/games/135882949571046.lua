local Yield = task.wait
local plr = game:GetService("Players").LocalPlayer
local repStorage = game:GetService("ReplicatedStorage")
local env = getgenv()

env.farming = false

local Rayfield = loadstring(game:HttpGet("https://sirius.menu/rayfield"))()

local Window = Rayfield:CreateWindow({
   Name = "zurai02",
   LoadingTitle = "Loading Script...",
   LoadingSubtitle = "by zurai02",
   ConfigurationSaving = {
      Enabled = true,
      FolderName = "BrainrotPolice",
      FileName = "DreamForBrainrotsConfig"
   }
})

local MainTab = Window:CreateTab("Main", 4483362458)
local PlayerTab = Window:CreateTab("Player", 4483362458)

MainTab:CreateSection("Farming Options")

MainTab:CreateToggle({
   Name = "Farming",
   CurrentValue = false,
   Flag = "DreamFarmingToggle",
   Callback = function(v)
      env.farming = v
      if not v then return end

      task.spawn(function()
         while env.farming do
            pcall(function()
               local remotes = repStorage:FindFirstChild("Remotes")
               if remotes then
                  local dreamState = remotes:FindFirstChild("DreamStateChanged")
                  local reqBrainrots = remotes:FindFirstChild("RequestDreamBrainrots")
                  local pickupBrainrot = remotes:FindFirstChild("PickupDreamBrainrot")
                  local exitWall = remotes:FindFirstChild("RequestDreamWallExit")

                  if dreamState then dreamState:FireServer(true) end
                  if reqBrainrots then reqBrainrots:FireServer() end
                  if pickupBrainrot then pickupBrainrot:FireServer("60") end

                  Yield()

                  if exitWall then exitWall:FireServer() end
               end
            end)
            Yield()
         end
      end)
   end,
})

PlayerTab:CreateSection("Player Tweaks")

PlayerTab:CreateSlider({
   Name = "WalkSpeed",
   Range = {16, 250},
   Increment = 1,
   Suffix = "Speed",
   CurrentValue = 16,
   Flag = "SpeedSlider",
   Callback = function(val)
      if plr.Character and plr.Character:FindFirstChildOfClass("Humanoid") then
         plr.Character:FindFirstChildOfClass("Humanoid").WalkSpeed = val
      end
   end,
})

PlayerTab:CreateSlider({
   Name = "JumpPower",
   Range = {50, 300},
   Increment = 5,
   Suffix = "Power",
   CurrentValue = 50,
   Flag = "JumpSlider",
   Callback = function(val)
      if plr.Character and plr.Character:FindFirstChildOfClass("Humanoid") then
         local hum = plr.Character:FindFirstChildOfClass("Humanoid")
         hum.UseJumpPower = true
         hum.JumpPower = val
      end
   end,
})
