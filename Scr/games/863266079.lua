local Bullets = require(game:GetService("ReplicatedStorage").Client.Libraries.Bullets)
local originalFire = Bullets.Fire
local TARGET_MAX_DIST = 500

local CONFIG = {
    Enabled = true
}

local localPlayer = game.Players.LocalPlayer
local TweenService = game:GetService("TweenService")
local Workspace = game:GetService("Workspace")

local screenGui = Instance.new("ScreenGui")
screenGui.Name = "BulletsConfigGui"
screenGui.ResetOnSpawn = false
screenGui.Parent = localPlayer:WaitForChild("PlayerGui")

local toggleButton = Instance.new("TextButton")
toggleButton.Name = "ToggleButton"
toggleButton.Size = UDim2.new(0, 140, 0, 45)
toggleButton.Position = UDim2.new(0, 20, 0, 20)
toggleButton.BackgroundColor3 = Color3.fromRGB(40, 160, 60)
toggleButton.TextColor3 = Color3.fromRGB(255, 255, 255)
toggleButton.TextSize = 14
toggleButton.Font = Enum.Font.GothamBold
toggleButton.Text = "Enabled: ON"
toggleButton.Parent = screenGui

local uiCorner = Instance.new("UICorner")
uiCorner.CornerRadius = UDim.new(0, 8)
uiCorner.Parent = toggleButton

local tweenInfo = TweenInfo.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out)

toggleButton.MouseButton1Click:Connect(function()
    CONFIG.Enabled = not CONFIG.Enabled
    local targetColor = CONFIG.Enabled and Color3.fromRGB(40, 160, 60) or Color3.fromRGB(180, 40, 40)
    local targetText = CONFIG.Enabled and "Enabled: ON" or "Enabled: OFF"
    toggleButton.Text = targetText
    TweenService:Create(toggleButton, tweenInfo, {BackgroundColor3 = targetColor}):Play()
end)

function Bullets.Fire(self, playerController, weaponInstance, weaponData, origin, direction, shotId)
    local newDirection = direction
    
    if CONFIG.Enabled then
        local mouse = localPlayer:GetMouse()
        local camera = Workspace.CurrentCamera
        local ray = camera:ScreenPointToRay(mouse.X, mouse.Y)
        local raycastParams = RaycastParams.new()
        raycastParams.FilterType = Enum.RaycastFilterType.Blacklist
        raycastParams.FilterDescendantsInstances = {localPlayer.Character}
        local rayResult = Workspace:Raycast(ray.Origin, ray.Direction * 1000, raycastParams)
        local hitPoint = rayResult and rayResult.Position or ray.Origin + ray.Direction * 1000
        local closestHRP = nil
        local closestDist = math.huge
        
        local charactersFolder = Workspace:FindFirstChild("Characters")
        if charactersFolder then
            for _, model in ipairs(charactersFolder:GetChildren()) do
                local hrp = model:FindFirstChild("HumanoidRootPart")
                if hrp and model ~= localPlayer.Character then
                    local dist = (hrp.Position - hitPoint).Magnitude
                    if dist < closestDist then
                        closestDist = dist
                        closestHRP = hrp
                    end
                end
            end
        end
        
        local zombiesFolder = Workspace:FindFirstChild("Zombies")
        if zombiesFolder then
            for _, model in ipairs(zombiesFolder:GetChildren()) do
                local hrp = model:FindFirstChild("HumanoidRootPart")
                if hrp then
                    local dist = (hrp.Position - hitPoint).Magnitude
                    if dist < closestDist then
                        closestDist = dist
                        closestHRP = hrp
                    end
                end
            end
        end
        
        if closestHRP and closestDist < TARGET_MAX_DIST then
            newDirection = (closestHRP.Position - origin).Unit
        end
    end
    
    return originalFire(self, playerController, weaponInstance, weaponData, origin, newDirection, shotId)
end