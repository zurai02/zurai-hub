local function GetSeedStock(IgnoreNoStock: boolean?): table
	local SeedShop = PlayerGui:FindFirstChild("Seed_Shop")
	if not SeedShop then return {} end
	
	local ItemFrame = SeedShop:FindFirstChild("Blueberry", true)
	if not ItemFrame then return {} end
	local Items = ItemFrame.Parent

	local NewList = {}
	local KeysList = {}

	for _, Item in next, Items:GetChildren() do
		local MainFrame = Item:FindFirstChild("Main_Frame")
		if not MainFrame then continue end

		local StockText = MainFrame.Stock_Text.Text
		local StockCount = tonumber(StockText:match("%d+")) or 0

		if IgnoreNoStock then
			if StockCount > 0 then
				NewList[Item.Name] = StockCount
				table.insert(KeysList, Item.Name)
			end
		else
			SeedStock[Item.Name] = StockCount
			table.insert(KeysList, Item.Name)
		end
	end

	return IgnoreNoStock and KeysList or KeysList
end

local function CanHarvest(Plant): boolean?
	local Prompt = Plant:FindFirstChildOfClass("ProximityPrompt") or Plant:FindFirstChild("ProximityPrompt", true)
	if not Prompt or not Prompt.Enabled then return end
	return true
end

local function CollectHarvestable(Parent, Plants, IgnoreDistance: boolean?)
	local Character = LocalPlayer.Character
	if not Character or not Character:FindFirstChild("HumanoidRootPart") then return Plants end
	local PlayerPosition = Character:GetPivot().Position

	for _, Plant in next, Parent:GetChildren() do
		local Fruits = Plant:FindFirstChild("Fruits")
		if Fruits then
			CollectHarvestable(Fruits, Plants, IgnoreDistance)
		end

		local PlantPosition = Plant:GetPivot().Position
		local Distance = (PlayerPosition - PlantPosition).Magnitude
		if not IgnoreDistance and Distance > 15 then continue end

		local Variant = Plant:FindFirstChild("Variant")
		if Variant and HarvestIgnores[Variant.Value] then continue end

		if CanHarvest(Plant) then
			table.insert(Plants, Plant)
		end
	end
	return Plants
end

local function GetHarvestablePlants(IgnoreDistance: boolean?)
	local Plants = {}
	if PlantsPhysical then
		CollectHarvestable(PlantsPhysical, Plants, IgnoreDistance)
	end
	return Plants
end

local function HarvestPlants()
	local Plants = GetHarvestablePlants()
	for _, Plant in next, Plants do
		HarvestPlant(Plant)
	end
end

local function AutoSellCheck()
	local CropCount = #GetInvCrops()

	if not Config.AutoSell then return end
	if CropCount < Config.SellThreshold then return end

	SellInventory()
end

local StatusLabel -- UI Label reference

local function AutoWalkLoop()
	if IsSelling then return end

	local Character = LocalPlayer.Character
	if not Character then return end
	local Humanoid = Character:FindFirstChildOfClass("Humanoid")
	if not Humanoid then return end

	local Plants = GetHarvestablePlants(true)
	local RandomAllowed = Config.AutoWalkAllowRandom
	local DoRandom = #Plants == 0 or math.random(1, 3) == 2

	if RandomAllowed and DoRandom then
		local Position = GetRandomFarmPoint()
		Humanoid:MoveTo(Position)
		if StatusLabel then StatusLabel:Set("Status: Random point") end
		return
	end
   
	for _, Plant in next, Plants do
		local Position = Plant:GetPivot().Position
		Humanoid:MoveTo(Position)
		if StatusLabel then StatusLabel:Set("Status: " .. Plant.Name) end
	end
end

local function NoclipLoop()
	local Character = LocalPlayer.Character
	if not Config.NoClip or not Character then return end

	for _, Part in Character:GetDescendants() do
		if Part:IsA("BasePart") then
			Part.CanCollide = false
		end
	end
end

local function MakeLoop(CheckKey, Func)
	task.spawn(function()
		while task.wait(0.01) do
			if Config[CheckKey] then
				Func()
			end
		end
	end)
end

