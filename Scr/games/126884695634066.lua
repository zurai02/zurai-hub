local function GetRandomFarmPoint(): Vector3
	if not PlantLocations then return Vector3.zero end
	local FarmLands = PlantLocations:GetChildren()
	if #FarmLands == 0 then return Vector3.zero end
	
	local FarmLand = FarmLands[math.random(1, #FarmLands)]

	local pX1, pZ1, pX2, pZ2 = GetArea(FarmLand)
	local X = math.random(pX1, pX2)
	local Z = math.random(pZ1, pZ2)

	return Vector3.new(X, 4, Z)
end

local function AutoPlantLoop()
	local Seed = Config.SelectedSeed
	if Seed == "" then return end

	local SeedData = OwnedSeeds[Seed]
	if not SeedData then return end

	local Count = SeedData.Count
	local Tool = SeedData.Tool

	if Count <= 0 then return end

	local Planted = 0
	local Step = 1

	EquipCheck(Tool)

	if Config.AutoPlantRandom then
		for i = 1, Count do
			local Point = GetRandomFarmPoint()
			Plant(Point, Seed)
		end
		return
	end
	
	for X = X1, X2, Step do
		for Z = Z1, Z2, Step do
			if Planted >= Count then break end
			local Point = Vector3.new(X, 0.13, Z)

			Planted += 1
			Plant(Point, Seed)
		end
	end
end

