local function StartServices()
	-- Auto-Walk Loop
	task.spawn(function()
		while yield(0.01) do
			if Config.AutoWalk then
				AutoWalkLoop()
				task.wait(math.random(1, Config.AutoWalkMaxWait))
			end
		end
	end)

	-- Auto-Harvest Loop
	MakeLoop("AutoHarvest", function()
		HarvestPlants()
	end)

	-- Auto-Buy Loop
	MakeLoop("AutoBuy", BuyAllSelectedSeeds)

	-- Auto-Plant Loop
	MakeLoop("AutoPlant", AutoPlantLoop)

	-- Background Sync Loop (Stock & Inventory)
	task.spawn(function()
		while task.wait(0.5) do
			GetSeedStock()
			GetOwnedSeeds()
		end
	end)
end

