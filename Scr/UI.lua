			Position=UDim2.fromOffset(mp.X,mp.Y),
			Size=UDim2.new(0,180,0,0),AutomaticSize=Enum.AutomaticSize.Y,
			ZIndex=80,Parent=self.ScreenGui},{
			Create("UICorner",{CornerRadius=UDim.new(0,12)}),
			Create("UIStroke",{Color=t.StrokeStrong,Thickness=1}),
			Create("UIListLayout",{Padding=UDim.new(0,2),SortOrder=Enum.SortOrder.LayoutOrder}),
			Create("UIPadding",{PaddingLeft=UDim.new(0,4),PaddingRight=UDim.new(0,4),PaddingTop=UDim.new(0,4),PaddingBottom=UDim.new(0,4)}),
		})
		TopHL(menu,80)
		-- Scale-in entrance
		local sc=Create("UIScale",{Scale=.9,Parent=menu})
		menu.BackgroundTransparency=1
		Tween(sc,{Scale=1},.15,Enum.EasingStyle.Back,Enum.EasingDirection.Out)
		Tween(menu,{BackgroundTransparency=0},.12)

		local function close()
			Tween(sc,{Scale=.9},.10); Tween(menu,{BackgroundTransparency=1},.10)
			task.delay(.11,function() pcall(menu.Destroy,menu) end)
		end

		for _,item in ipairs(items) do
			if item=="---" then
				Create("Frame",{BackgroundColor3=t.Stroke,Size=UDim2.new(1,0,0,1),BorderSizePixel=0,ZIndex=81,Parent=menu})
			else
				local tc=item.Danger and t.Danger or t.Text
				local row=Create("TextButton",{
					Text=(item.Icon and item.Icon.."  " or "")..tostring(item.Label or ""),
					Font=Enum.Font.Gotham,TextSize=13,TextColor3=tc,
					TextXAlignment=Enum.TextXAlignment.Left,
					BackgroundColor3=t.Secondary,BackgroundTransparency=1,
					Size=UDim2.new(1,0,0,30),ZIndex=81,Parent=menu,
				},{Create("UICorner",{CornerRadius=UDim.new(0,8)}),Create("UIPadding",{PaddingLeft=UDim.new(0,10)})})
				row.MouseEnter:Connect(function() Tween(row,{BackgroundTransparency=.6,BackgroundColor3=item.Danger and t.DangerBg or t.Elevated},.08) end)
				row.MouseLeave:Connect(function() Tween(row,{BackgroundTransparency=1},.12) end)
				row.MouseButton1Click:Connect(function()
					close()
					if item.Callback then task.spawn(item.Callback) end
				end)
			end
		end

		-- Close on outside click
		local conn; conn=UserInputService.InputBegan:Connect(function(inp)
			if inp.UserInputType==Enum.UserInputType.MouseButton1 then
				task.defer(function()
					local m=UserInputService:GetMouseLocation()
					local ap=menu.AbsolutePosition; local as=menu.AbsoluteSize
					if m.X<ap.X or m.X>ap.X+as.X or m.Y<ap.Y or m.Y>ap.Y+as.Y then
						close(); conn:Disconnect()
					end
				end)
			end
		end)
		track(conn)
		return {Close=close}
	end

	table.insert(NovaUI.Windows, Window)
	return Window
end

