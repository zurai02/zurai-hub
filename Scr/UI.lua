		if _dragMove and (inp.UserInputType==Enum.UserInputType.MouseMovement or
			inp.UserInputType==Enum.UserInputType.Touch) then _dragMove(inp) end
	end))
	track(UserInputService.InputEnded:Connect(function(inp)
		if _dragEnd and (inp.UserInputType==Enum.UserInputType.MouseButton1 or
			inp.UserInputType==Enum.UserInputType.Touch) then
			local fn=_dragEnd; _dragMove=nil; _dragEnd=nil; fn(inp)
		end
