-- Scale-squish press with held-state guard
local function PressAnim(btn)
	local sc=Create("UIScale",{Scale=1,Parent=btn})
	local held=false
	btn.MouseButton1Down:Connect(function() held=true; Tween(sc,{Scale=.96},.07,Enum.EasingStyle.Quad) end)
	local function up() if held then held=false; Tween(sc,{Scale=1},.20,Enum.EasingStyle.Back,Enum.EasingDirection.Out) end end
	btn.MouseButton1Up:Connect(up)
	btn.MouseLeave:Connect(function() if not held then Tween(sc,{Scale=1},.20,Enum.EasingStyle.Back,Enum.EasingDirection.Out) end end)
end

-- Ripple from cursor
local function Ripple(parent, pos, color)
	color=color or Color3.new(1,1,1)
	local abs,sz = parent.AbsolutePosition, parent.AbsoluteSize
	local maxR = math.sqrt(sz.X^2+sz.Y^2)*1.2
	local c=Create("Frame",{
		Name="Ripple", AnchorPoint=Vector2.new(.5,.5),
		Position=UDim2.new(0,pos.X-abs.X,0,pos.Y-abs.Y),
		Size=UDim2.new(0,4,0,4),
		BackgroundColor3=color, BackgroundTransparency=.7,
		BorderSizePixel=0, ZIndex=(parent.ZIndex or 1)+6, Parent=parent,
	},{Create("UICorner",{CornerRadius=UDim.new(1,0)})})
	Tween(c,{Size=UDim2.new(0,maxR*2,0,maxR*2),BackgroundTransparency=1},.55,Enum.EasingStyle.Quint)
	task.delay(.56,function() pcall(c.Destroy,c) end)
end

