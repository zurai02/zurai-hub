function NovaUI:GetFlag(f) return NovaUI.Flags[f] end
function NovaUI:SetFlag(f,v)
	NovaUI.Flags[f]=v
	local cb=NovaUI._callbacks[f]
	if cb then for _,fn in ipairs(cb) do task.spawn(fn,v) end end
end
function NovaUI:OnFlagChanged(f,cb)
	if not NovaUI._callbacks[f] then NovaUI._callbacks[f]={} end
	table.insert(NovaUI._callbacks[f],cb)
end
function NovaUI:ResetFlags()
	for f in pairs(NovaUI.Flags) do
		NovaUI.Flags[f]=nil
		local cb=NovaUI._callbacks[f]
		if cb then for _,fn in ipairs(cb) do task.spawn(fn,nil) end end
	end
end
function NovaUI:SetGlobalTheme(name)
	for _,w in ipairs(NovaUI.Windows) do w:SetTheme(name) end
end

