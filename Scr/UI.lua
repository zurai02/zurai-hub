		local stroke=Main:FindFirstChildOfClass("UIStroke")
		if stroke then stroke.Color=t.StrokeStrong end
		-- Broadcast to all registered component updaters
		for _,fn in ipairs(_themeListeners) do pcall(fn,t) end
	end

	function Window:GetTab(name)
		for _,tab in ipairs(self._tabs) do
			if tab._name==name then return tab end
		end
	end

	function Window:RemoveTab(name)
		for i,tab in ipairs(self._tabs) do
			if tab._name==name then
				tab.Page:Destroy(); tab.Button:Destroy()
				table.remove(self._tabs,i)
				-- select first remaining
				if self._firstTab==tab and self._tabs[1] then
					self._firstTab=nil
					self._tabs[1].Button.MouseButton1Click:Fire()
				end
				return
			end
		end
	end

	function Window:GetComponent(flag)
		return _components[flag]
	end

	function Window:Destroy()
		for _,c in ipairs(self._connections) do
			if typeof(c)=="RBXScriptConnection" and c.Connected then c:Disconnect() end
		end
		table.clear(self._connections)
		if self.ScreenGui then self.ScreenGui:Destroy() end
		for i,w in ipairs(NovaUI.Windows) do
			if w==self then table.remove(NovaUI.Windows,i); break end
		end
	end

