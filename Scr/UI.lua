		if SO then Tween(SO,{BackgroundTransparency=1-(1-.70)*(1-alpha)},dur) end
		if SI then Tween(SI,{BackgroundTransparency=1-(1-.45)*(1-alpha)},dur) end
	end
	setShadow(1)

