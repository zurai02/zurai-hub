	function Window:SetTheme(nameOrTable)
		local t=typeof(nameOrTable)=="table" and FinalizeTheme(nameOrTable) or (Themes[nameOrTable] or Themes.Dark)
		self.Theme=t; theme=t
		Main.BackgroundColor3=t.Background
