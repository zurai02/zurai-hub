			local function multiText()
				local n=0; for _ in pairs(selected) do n+=1 end
				if n==0 then return "None"
				elseif n==1 then for v in pairs(selected) do return v end
				else return n.." selected" end
			end
			local valLbl=Create("TextLabel",{
				Text=multi and multiText() or tostring(current or ""),
				Font=Enum.Font.Gotham,TextSize=12,TextColor3=theme.SubText,
				TextXAlignment=Enum.TextXAlignment.Right,BackgroundTransparency=1,
				Position=UDim2.new(.55,0,0,0),Size=UDim2.new(.45,-30,0,38),ZIndex=z+2,Parent=head})
			local chevron=Create("TextLabel",{Text="▾",Font=Enum.Font.GothamBold,TextSize=12,
				TextColor3=theme.SubText,BackgroundTransparency=1,AnchorPoint=Vector2.new(1,.5),
				Position=UDim2.new(1,-14,.5,0),Size=UDim2.new(0,14,0,14),ZIndex=z+2,Parent=head})
			Create("Frame",{Position=UDim2.new(0,10,0,38),Size=UDim2.new(1,-20,0,1),
				BackgroundColor3=theme.Stroke,BorderSizePixel=0,ZIndex=z+1,Parent=holder})
			local listHolder=Create("Frame",{
				Position=UDim2.new(0,4,0,42),Size=UDim2.new(1,-8,0,0),
				BackgroundTransparency=1,ZIndex=z+1,Parent=holder,
			})
			Create("UIListLayout",{Padding=UDim.new(0,2),SortOrder=Enum.SortOrder.LayoutOrder,Parent=listHolder})

			local function rebuild()
				for _,c in ipairs(listHolder:GetChildren()) do if c:IsA("TextButton") then c:Destroy() end end
				for _,opt in ipairs(options) do
					local isSel=multi and selected[opt]==true or (not multi and current==opt)
					local row=Create("TextButton",{
						Text=(isSel and "✓  " or "    ")..tostring(opt),
						Font=Enum.Font.Gotham,TextSize=12,
						TextColor3=isSel and theme.Accent or theme.SubText,
						TextXAlignment=Enum.TextXAlignment.Left,
						BackgroundColor3=theme.Elevated,BackgroundTransparency=isSel and .55 or 1,
						Size=UDim2.new(1,0,0,28),ZIndex=z+2,Parent=listHolder,
					},{Create("UICorner",{CornerRadius=UDim.new(0,8)}),Create("UIPadding",{PaddingLeft=UDim.new(0,10)})})
					row.MouseEnter:Connect(function() Tween(row,{BackgroundTransparency=.45,BackgroundColor3=theme.ElevatedHover},.08) end)
					row.MouseLeave:Connect(function() Tween(row,{BackgroundTransparency=isSel and .55 or 1},.12) end)
					row.MouseButton1Click:Connect(function()
						if multi then
							if selected[opt] then selected[opt]=nil else selected[opt]=true end
							valLbl.Text=multiText()
							local l={}; for v in pairs(selected) do table.insert(l,v) end
							NovaUI:SetFlag(opts.Flag,l)
							if opts.Callback then task.spawn(opts.Callback,l) end
							rebuild()
						else
							current=opt; valLbl.Text=tostring(opt)
							NovaUI:SetFlag(opts.Flag,opt)
							if opts.Callback then task.spawn(opts.Callback,opt) end
							open=false; Tween(holder,{Size=UDim2.new(1,0,0,38)},.16); Tween(chevron,{Rotation=0},.16)
							rebuild()
						end
					end)
				end
			end
			rebuild()

			-- Close on outside click (deferred so AbsolutePosition is valid)
			track(UserInputService.InputBegan:Connect(function(inp)
				if not open then return end
				if inp.UserInputType==Enum.UserInputType.MouseButton1 then
					task.defer(function()
						local mp=UserInputService:GetMouseLocation()
						local ap=holder.AbsolutePosition; local as=holder.AbsoluteSize
						if mp.X<ap.X or mp.X>ap.X+as.X or mp.Y<ap.Y or mp.Y>ap.Y+as.Y then
							open=false; Tween(holder,{Size=UDim2.new(1,0,0,38)},.16); Tween(chevron,{Rotation=0},.16)
						end
					end)
				end
			end))

