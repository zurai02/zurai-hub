local function Create(cls, props, children)
	local i = Instance.new(cls)
	for k,v in pairs(props or {}) do i[k]=v end
	for _,c in ipairs(children or {}) do c.Parent=i end
	return i
end

-- Cached TweenInfo pool
local _ti = {}
local function TI(dur, style, dir)
	dur   = dur   or 0.22
	style = style or Enum.EasingStyle.Quint
	dir   = dir   or Enum.EasingDirection.Out
	local k = dur.."|"..style.Value.."|"..dir.Value
	if not _ti[k] then _ti[k]=TweenInfo.new(dur,style,dir) end
	return _ti[k]
end
local function Tween(obj, goal, dur, style, dir)
	local t = TweenService:Create(obj, TI(dur,style,dir), goal)
	t:Play(); return t
end

-- Colour helpers
local function Lighten(c,a) a=a or .07
	local h,s,v=c:ToHSV()
	return Color3.fromHSV(h,math.max(0,s-a*.25),math.clamp(v+a,0,1)) end
local function Darken(c,a) a=a or .07
	local h,s,v=c:ToHSV()
	return Color3.fromHSV(h,math.min(1,s+a*.15),math.clamp(v-a,0,1)) end
local function Hex(c)
	return ("#%02X%02X%02X"):format(
		math.floor(c.R*255+.5),math.floor(c.G*255+.5),math.floor(c.B*255+.5)) end
local function FromHex(s)
	s=s:gsub("^#","")
	if #s~=6 then return Color3.new(1,1,1) end
	return Color3.fromRGB(
		tonumber(s:sub(1,2),16)or 0,
		tonumber(s:sub(3,4),16)or 0,
		tonumber(s:sub(5,6),16)or 0) end
local function LerpC(a,b,t)
	return Color3.new(a.R+(b.R-a.R)*t,a.G+(b.G-a.G)*t,a.B+(b.B-a.B)*t) end

