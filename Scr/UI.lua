		-- ── Slider ────────────────────────────────────────────────────────
		function Tab:CreateSlider(opts)
			opts=opts or {}; local z=newZi()
			local mn=(opts.Range and opts.Range[1]) or 0
			local mx=(opts.Range and opts.Range[2]) or 100
			local inc=opts.Increment or 1
