--// ─────────────────────────── SERIALIZATION ─────────────────────────────── //

local function sv(v)
	local t=typeof(v)
	if t=="Color3" then return{__type="Color3",r=v.R,g=v.G,b=v.B}
	elseif t=="EnumItem" then return{__type="Enum",enum=tostring(v.EnumType),name=v.Name}
	elseif t=="Vector2" then return{__type="V2",x=v.X,y=v.Y}
	elseif t=="Vector3" then return{__type="V3",x=v.X,y=v.Y,z=v.Z}
	else return v end
end
local function dv(v)
	if typeof(v)~="table" then return v end
	if v.__type=="Color3" then return Color3.new(v.r,v.g,v.b)
	elseif v.__type=="V2" then return Vector2.new(v.x,v.y)
	elseif v.__type=="V3" then return Vector3.new(v.x,v.y,v.z)
	elseif v.__type=="Enum" then local ok,i=pcall(function() return Enum[v.enum][v.name] end); return ok and i or nil end
	return v
end

function NovaUI:ExportConfig()
	local s={}; for f,val in pairs(NovaUI.Flags) do s[f]=sv(val) end
	local ok,enc=pcall(function() return HttpService:JSONEncode(s) end)
	return ok and enc or nil
end
function NovaUI:ImportConfig(json)
	local ok,dec=pcall(function() return HttpService:JSONDecode(json) end)
	if not ok or typeof(dec)~="table" then return false end
	for f,val in pairs(dec) do NovaUI:SetFlag(f,dv(val)) end
	return true
end

