		Tween(Main,{Size=fx,BackgroundTransparency=0},.32,Enum.EasingStyle.Back,Enum.EasingDirection.Out)
		fadeShadow(0,.40)
		for _,s in ipairs(Main:GetChildren()) do if s:IsA("UIStroke") then Tween(s,{Transparency=0},.34) end end
