		local function selectTab()
			for _,t in pairs(Window._tabs) do
				t.Page.Visible=false; t.Selected=false
				Tween(t.Button,{BackgroundTransparency=1,TextColor3=theme.SubText},.14)
				local ind=t.Button:FindFirstChild("Indicator")
				if ind then Tween(ind,{Size=UDim2.new(0,3,0,0)},.14,Enum.EasingStyle.Quad) end
				local img=t.Button:FindFirstChildOfClass("ImageLabel")
				if img then Tween(img,{ImageColor3=theme.SubText},.14) end
			end
