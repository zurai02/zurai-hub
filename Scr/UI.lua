				Size=UDim2.new(1,-28,0,18),ZIndex=z+1,Parent=holder})
			Tooltip(holder,theme,opts.Info)
			local valLbl=Create("TextLabel",{Text=tostring(val),Font=Enum.Font.GothamBold,TextSize=12,
				TextColor3=theme.Accent,TextXAlignment=Enum.TextXAlignment.Right,
				BackgroundTransparency=1,Position=UDim2.new(0,14,0,8),
				Size=UDim2.new(1,-28,0,18),ZIndex=z+1,Parent=holder})
			local track=Create("Frame",{
				Position=UDim2.new(0,14,0,38),Size=UDim2.new(1,-28,0,5),
				BackgroundColor3=theme.Stroke,ZIndex=z+1,Parent=holder,
			},{Create("UICorner",{CornerRadius=UDim.new(1,0)})})
			local fill=Create("Frame",{
				Size=UDim2.new((val-mn)/(mx-mn),0,1,0),BackgroundColor3=theme.Accent,
				ZIndex=z+2,Parent=track,
			},{
				Create("UICorner",{CornerRadius=UDim.new(1,0)}),
				Create("UIGradient",{Color=ColorSequence.new(theme.AccentDark,theme.AccentLight)}),
			})
			local thumb=Create("Frame",{
				AnchorPoint=Vector2.new(.5,.5),
				Position=UDim2.new((val-mn)/(mx-mn),0,.5,0),
				Size=UDim2.new(0,16,0,16),BackgroundColor3=Color3.new(1,1,1),
				ZIndex=z+3,Parent=track,
			},{
				Create("UICorner",{CornerRadius=UDim.new(1,0)}),
				Create("UIStroke",{Color=theme.Accent,Thickness=2.5}),
			})

			local function quantize(raw)
				raw=math.floor(raw/inc+.5)*inc
				return math.clamp(raw,mn,mx)
			end
			local function fireIfChanged(v)
				if v~=lastFired then lastFired=v; NovaUI:SetFlag(opts.Flag,v); if opts.Callback then task.spawn(opts.Callback,v) end end
			end
			local function setAlpha(a,noTween)
				a=Clamp01(a)
				val=quantize(mn+(mx-mn)*a)
				valLbl.Text=tostring(Round(val,2))
				local fa=(val-mn)/(mx-mn)
				if noTween then fill.Size=UDim2.new(fa,0,1,0); thumb.Position=UDim2.new(fa,0,.5,0)
				else Tween(fill,{Size=UDim2.new(fa,0,1,0)},.07); Tween(thumb,{Position=UDim2.new(fa,0,.5,0)},.07) end
				fireIfChanged(val)
			end
			track.InputBegan:Connect(function(inp)
				if inp.UserInputType==Enum.UserInputType.MouseButton1 or inp.UserInputType==Enum.UserInputType.Touch then
					Tween(thumb,{Size=UDim2.new(0,20,0,20)},.10)
					setAlpha((inp.Position.X-track.AbsolutePosition.X)/track.AbsoluteSize.X,true)
					beginDrag(function(mi) setAlpha((mi.Position.X-track.AbsolutePosition.X)/track.AbsoluteSize.X,true) end,
					function() Tween(thumb,{Size=UDim2.new(0,16,0,16)},.15); fireIfChanged(val) end)
				end
			end)
			if opts.Flag then NovaUI.Flags[opts.Flag]=val end
			local api={Set=function(v) setAlpha((v-mn)/(mx-mn)) end, Get=function() return val end}
			if opts.Flag then _components[opts.Flag]=api end
			return api
		end

		-- ── Step slider (snaps to labelled stops) ─────────────────────────
		-- opts: Name, Steps={string,...}, DefaultStep (index), Flag, Callback
		function Tab:CreateStepSlider(opts)
			opts=opts or {}; local z=newZi()
			local steps=opts.Steps or {"Low","Medium","High"}
			local nSteps=#steps
			local cur=math.clamp(opts.DefaultStep or 1,1,nSteps)

			local holder=Create("Frame",{
				BackgroundColor3=theme.Elevated,Size=UDim2.new(1,0,0,60),ZIndex=z,Parent=Page,
			},{
				Create("UICorner",{CornerRadius=UDim.new(0,12)}),
				Create("UIStroke",{Color=theme.Stroke,Thickness=1}),
			})
			TopHL(holder,z)
			Create("TextLabel",{Text=opts.Name or "Step",Font=Enum.Font.GothamMedium,TextSize=13,
				TextColor3=theme.Text,TextXAlignment=Enum.TextXAlignment.Left,
				BackgroundTransparency=1,Position=UDim2.new(0,14,0,8),
				Size=UDim2.new(.6,0,0,18),ZIndex=z+1,Parent=holder})
			local valLbl=Create("TextLabel",{Text=steps[cur],Font=Enum.Font.GothamBold,TextSize=12,
				TextColor3=theme.Accent,TextXAlignment=Enum.TextXAlignment.Right,
				BackgroundTransparency=1,Position=UDim2.new(0,14,0,8),
				Size=UDim2.new(1,-28,0,18),ZIndex=z+1,Parent=holder})

			-- Track with segment markers
			local track=Create("Frame",{
				Position=UDim2.new(0,14,0,38),Size=UDim2.new(1,-28,0,4),
				BackgroundColor3=theme.Stroke,ZIndex=z+1,Parent=holder,
			},{Create("UICorner",{CornerRadius=UDim.new(1,0)})})
			local fill=Create("Frame",{
				Size=UDim2.new((cur-1)/(nSteps-1),0,1,0),BackgroundColor3=theme.Accent,
				ZIndex=z+2,Parent=track,
			},{Create("UICorner",{CornerRadius=UDim.new(1,0)})})

			-- Stop dots
			local dots={}
			for i=1,nSteps do
				local a=(i-1)/(nSteps-1)
				local d=Create("Frame",{
					AnchorPoint=Vector2.new(.5,.5),Position=UDim2.new(a,0,.5,0),
					Size=UDim2.new(0,10,0,10),
					BackgroundColor3=i<=cur and theme.Accent or theme.Stroke,
					ZIndex=z+3,Parent=track,
				},{Create("UICorner",{CornerRadius=UDim.new(1,0)})})
				dots[i]=d
			end
			-- Draggable thumb
			local thumb=Create("Frame",{
				AnchorPoint=Vector2.new(.5,.5),
				Position=UDim2.new((cur-1)/(nSteps-1),0,.5,0),
				Size=UDim2.new(0,18,0,18),BackgroundColor3=Color3.new(1,1,1),
				ZIndex=z+4,Parent=track,
			},{Create("UICorner",{CornerRadius=UDim.new(1,0)}),Create("UIStroke",{Color=theme.Accent,Thickness=2})})

			local function setCur(i)
				cur=math.clamp(i,1,nSteps)
				valLbl.Text=steps[cur]
				local a=(cur-1)/(nSteps-1)
				Tween(fill,{Size=UDim2.new(a,0,1,0)},.15)
				Tween(thumb,{Position=UDim2.new(a,0,.5,0)},.15,Enum.EasingStyle.Back,Enum.EasingDirection.Out)
				for j,d in ipairs(dots) do Tween(d,{BackgroundColor3=j<=cur and theme.Accent or theme.Stroke},.12) end
				NovaUI:SetFlag(opts.Flag,cur)
				if opts.Callback then task.spawn(opts.Callback,cur,steps[cur]) end
			end
			track.InputBegan:Connect(function(inp)
				if inp.UserInputType==Enum.UserInputType.MouseButton1 or inp.UserInputType==Enum.UserInputType.Touch then
					local a=Clamp01((inp.Position.X-track.AbsolutePosition.X)/track.AbsoluteSize.X)
					setCur(math.floor(a*(nSteps-1)+.5)+1)
					beginDrag(function(mi)
						local aa=Clamp01((mi.Position.X-track.AbsolutePosition.X)/track.AbsoluteSize.X)
						setCur(math.floor(aa*(nSteps-1)+.5)+1)
					end,function() end)
				end
			end)
			if opts.Flag then NovaUI.Flags[opts.Flag]=cur end
			local api={Set=function(i) setCur(i) end, Get=function() return cur,steps[cur] end}
			if opts.Flag then _components[opts.Flag]=api end
			return api
		end

		-- ── Dropdown ──────────────────────────────────────────────────────
		function Tab:CreateDropdown(opts)
			opts=opts or {}; local z=newZi()
			local options=opts.Options or {}
			local multi=opts.MultiSelect==true
			local current=opts.CurrentOption or options[1]
			local selected={}
