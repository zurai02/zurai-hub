				Get=function() local l={}; for v in pairs(selected) do table.insert(l,v) end; return l end,
				Set=function(vals) selected={}; for _,v in ipairs(vals) do selected[v]=true end; for _,o in ipairs(options) do updateChip(o) end end,
			}
