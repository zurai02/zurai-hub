				open=not open
				local h=open and (42+math.min(#options,8)*30+4) or 38
				Tween(holder,{Size=UDim2.new(1,0,0,h)},.18); Tween(chevron,{Rotation=open and 180 or 0},.18)
			end)

			if opts.Flag then
				if multi then local l={}; for v in pairs(selected) do table.insert(l,v) end; NovaUI.Flags[opts.Flag]=l
				else NovaUI.Flags[opts.Flag]=current end
			end
			local api={
				Set=function(v)
					if multi then selected={}; for _,x in ipairs(v) do selected[x]=true end
					else current=v end
					valLbl.Text=multi and multiText() or tostring(v); rebuild()
				end,
				Get=function()
					if multi then local l={}; for v in pairs(selected) do table.insert(l,v) end; return l end
					return current
				end,
				Refresh=function(newOpts)
					options=newOpts
					if not multi then
						local ok=false; for _,v in ipairs(options) do if v==current then ok=true; break end end
						if not ok then current=options[1] end
					else
						for v in pairs(selected) do
							local f=false; for _,nv in ipairs(options) do if nv==v then f=true; break end end
							if not f then selected[v]=nil end
						end
					end
					valLbl.Text=multi and multiText() or tostring(current or ""); rebuild()
				end,
			}
			if opts.Flag then _components[opts.Flag]=api end
			return api
		end

