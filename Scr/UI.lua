			AutomaticSize=Enum.AutomaticSize.Y,Size=UDim2.new(1,0,0,0),ZIndex=31}),
	})
	local tipStroke=tip:FindFirstChildOfClass("UIStroke")

	badge.MouseEnter:Connect(function()
		local sY=badge.AbsolutePosition.Y
		local vp=workspace.CurrentCamera.ViewportSize
		if sY < vp.Y*.35 then
			tip.AnchorPoint=Vector2.new(.5,0); tip.Position=UDim2.new(.5,0,1,8)
		else
			tip.AnchorPoint=Vector2.new(.5,1); tip.Position=UDim2.new(.5,0,0,-8)
		end
		tip.Visible=true
		Tween(tip,{BackgroundTransparency=0},.12)
		if tipStroke then Tween(tipStroke,{Transparency=0},.12) end
	end)
	badge.MouseLeave:Connect(function()
		Tween(tip,{BackgroundTransparency=1},.10)
		if tipStroke then Tween(tipStroke,{Transparency=1},.10) end
		task.delay(.11,function() tip.Visible=false end)
	end)
end

-- Window drag (uses the caller's connections table)
local function MakeDraggable(handle, target, conns)
	local dragging,di,ds,sp
	local function push(c) table.insert(conns,c) end
	push(handle.InputBegan:Connect(function(inp)
		if inp.UserInputType==Enum.UserInputType.MouseButton1 or inp.UserInputType==Enum.UserInputType.Touch then
			dragging=true; ds=inp.Position; sp=target.Position
			inp.Changed:Connect(function() if inp.UserInputState==Enum.UserInputState.End then dragging=false end end)
		end
	end))
	push(handle.InputChanged:Connect(function(inp)
		if inp.UserInputType==Enum.UserInputType.MouseMovement or inp.UserInputType==Enum.UserInputType.Touch then di=inp end
	end))
	push(UserInputService.InputChanged:Connect(function(inp)
		if inp==di and dragging then
			local d=inp.Position-ds
			target.Position=UDim2.new(sp.X.Scale,sp.X.Offset+d.X,sp.Y.Scale,sp.Y.Offset+d.Y)
		end
	end))
end

